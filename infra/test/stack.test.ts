import * as cdk from 'aws-cdk-lib';
import { Template } from 'aws-cdk-lib/assertions';
import { strict as assert } from 'node:assert';
import * as cloudfront from 'aws-cdk-lib/aws-cloudfront';
import { CurtailIQStack } from '../lib/curtailiq-stack';

const app = new cdk.App();
const template = Template.fromStack(new CurtailIQStack(app, 'TestStack'));
const resources = template.toJSON().Resources;
const buckets = template.findResources('AWS::S3::Bucket');
assert.equal(Object.keys(buckets).length, 1);
assert.equal(Object.values(buckets)[0].DeletionPolicy, 'Retain', 'bucket deletion policy must retain data');
template.hasResourceProperties('AWS::S3::Bucket', { PublicAccessBlockConfiguration: { BlockPublicAcls: true, BlockPublicPolicy: true, IgnorePublicAcls: true, RestrictPublicBuckets: true } });
const bucketPolicy = Object.values(template.findResources('AWS::S3::BucketPolicy'))[0];
const tlsStatement = bucketPolicy.Properties.PolicyDocument.Statement.find((statement: any) => statement.Condition?.Bool?.['aws:SecureTransport'] === 'false');
assert.ok(tlsStatement, 'bucket policy must deny insecure transport');
assert.equal(tlsStatement.Effect, 'Deny');
template.hasResourceProperties('AWS::Logs::LogGroup', { RetentionInDays: 30 });
assert.equal(Object.values(template.findResources('AWS::Logs::LogGroup'))[0].DeletionPolicy, 'Retain');
const lambdaResources = Object.values(template.findResources('AWS::Lambda::Function'));
assert.equal(lambdaResources.length, 1);
const lambdaProperties = lambdaResources[0].Properties;
assert.equal(lambdaProperties.PackageType, 'Image');
assert.equal(lambdaProperties.Environment.Variables.CURTAILMENT_MODEL_MODE, 'base');
assert.equal(lambdaProperties.Environment.Variables.CURTAILMENT_MODEL_PATH, '/opt/curtailai-demo-disabled/base.pkl');
assert.equal(lambdaProperties.Environment.Variables.CURTAILMENT_MODEL_ADVANCED_PATH, '/opt/curtailai-demo-disabled/advanced.pkl');
assert.deepEqual(lambdaProperties.Architectures, ['x86_64']);
const parameters = template.toJSON().Parameters;
assert.equal(parameters.ImageDigest.AllowedPattern, '^sha256:[a-f0-9]{64}$');
assert.equal(parameters.ImageDigest.Default, undefined);
assert.equal(parameters.PermissionsBoundaryArn.Default, undefined);
assert.equal(lambdaProperties.Code.ImageUri['Fn::Join'][1].some((part: any) => typeof part === 'object' && part.Ref === 'ImageDigest'), true);
assert.ok(lambdaProperties.Code.ImageUri['Fn::Join'][1].includes('/curtailai/backend@'), 'ECR digest must use @sha256 syntax, not a mutable tag separator');
assert.equal(lambdaProperties.Handler, undefined);
assert.equal(lambdaProperties.Runtime, undefined);
assert.equal(lambdaProperties.Timeout, 60);
assert.equal(lambdaProperties.MemorySize, 1024);
template.resourceCountIs('AWS::Lambda::ProvisionedConcurrencyConfig', 0);
template.resourceCountIs('AWS::RDS::DBInstance', 0);
template.resourceCountIs('AWS::DynamoDB::Table', 0);
template.resourceCountIs('AWS::Redshift::Cluster', 0);
template.resourceCountIs('AWS::EC2::NatGateway', 0);
template.resourceCountIs('AWS::EC2::Instance', 0);
template.hasResourceProperties('AWS::Lambda::Function', { Environment: { Variables: { DATA_BACKEND: 'mock', BEDROCK_ENABLED: 'false' } } });
template.hasResourceProperties('AWS::Lambda::Url', { AuthType: 'NONE' });
const distributions = Object.values(template.findResources('AWS::CloudFront::Distribution'));
const distConfig = distributions[0].Properties.DistributionConfig;
const apiBehavior = distConfig.CacheBehaviors.find((behavior: any) => behavior.PathPattern === '/api/*');
assert.ok(apiBehavior, 'API behavior must route /api/*');
assert.equal(apiBehavior.CachePolicyId, cloudfront.CachePolicy.CACHING_DISABLED.cachePolicyId);
assert.equal(distConfig.CustomErrorResponses, undefined, 'SPA error rewrite must not mask API errors');
assert.equal(distConfig.DefaultCacheBehavior.ViewerProtocolPolicy, 'redirect-to-https');
const role = Object.values(template.findResources('AWS::IAM::Role'))[0];
assert.equal(role.Properties.RoleName['Fn::Join'][1][0], 'curtailai-demo-');
assert.equal(role.Properties.PermissionsBoundary.Ref, 'PermissionsBoundaryArn');
const policies = Object.values(template.findResources('AWS::IAM::Policy'));
assert.equal(policies.length, 1);
const statements = policies[0].Properties.PolicyDocument.Statement;
assert.deepEqual(statements.map((statement: any) => statement.Action), [['logs:CreateLogStream', 'logs:PutLogEvents']]);
assert.ok(resources);
console.log('CDK stack assertions passed');
